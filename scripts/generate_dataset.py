#!/usr/bin/env python3
"""Generate synthetic DSE memory records using Gemini for content generation.

Two generation modes:

  batch  — One API call produces N records as a JSON array (fewer calls, cheaper).
  async  — Each record is generated by its own API call, run concurrently with a
           semaphore (higher diversity, slower, more API usage).

Usage:
    python scripts/generate_dataset.py --num 100
    python scripts/generate_dataset.py --num 100 --mode async --concurrency 8
    python scripts/generate_dataset.py --num 10000 --persona "A frontend dev using React"

Environment:
    GEMINI_API_KEY  — required (or pass --api-key)
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
import time
import uuid
from datetime import UTC, datetime, timedelta
from pathlib import Path

import click

# Load .env from project root if present
_env_path = Path(__file__).resolve().parent.parent / ".env"
if _env_path.exists():
    for line in _env_path.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, _, v = line.partition("=")
            os.environ.setdefault(k.strip(), v.strip())

from google import genai

# ── Prompts ──────────────────────────────────────────────────────────────────

_FIELD_SPEC = """\
For EACH record, generate a JSON object with these fields:
- "content_text": string — the actual memory content (1-3 sentences, specific and realistic)
- "summary": string — a shorter version (max 150 chars)
- "memory_type": one of "episodic", "semantic", "procedural", "prospective"
- "memory_subtype": one of "observation", "inference", "user_explicit", "agent_generated"
- "confidence": float 0.6-1.0
- "source_type": one of "observation", "inference", "user_explicit", "external_api"
- "tags": array of 1-4 short lowercase tags
- "entities": array of 0-3 named entities (tools, models, people, etc.)"""

_DISTRIBUTION_RULES = """\
Distribution rules for memory_type:
- ~50% episodic (specific events: training runs, meetings, experiments, paper readings)
- ~30% semantic (lasting facts: best practices, domain knowledge, tool preferences)
- ~12% procedural (how-to rules: checklists, workflows, debugging steps)
- ~8% prospective (future tasks: deadlines, scheduled reviews, reminders)"""

_PROSPECTIVE_RULES = """\
For "prospective" memories:
- Add "trigger_type": "time" or "condition"
- Add "trigger_at": ISO 8601 datetime 1-60 days in the future from today ({today})
- If trigger_type is "condition", add "trigger_condition": a short condition string"""

_QUALITY_RULES = """\
Important:
- Make content SPECIFIC (include model names, metric values, dates, tool names)
- Vary the topics across the persona's work areas
- Each record should be UNIQUE — no duplicates
- Episodic memories should reference specific dates in the past year
- Semantic memories should be general knowledge the persona has accumulated
- Procedural memories should be step-by-step processes
- Return ONLY valid JSON, no markdown fences, no explanation"""


BATCH_PROMPT = """\
You are a synthetic data generator for a memory system called DSE.

Generate exactly {count} memory records as a JSON array.
Each record must be a realistic memory for this persona:

=== PERSONA ===
{persona}
===============

{field_spec}

{distribution_rules}

{prospective_rules}

{quality_rules}

Output: [{count} JSON objects]"""


SINGLE_PROMPT = """\
You are a synthetic data generator for a memory system called DSE.

Generate exactly ONE memory record as a JSON object for this persona:

=== PERSONA ===
{persona}
===============

The memory_type for this record MUST be: "{memory_type}"

{field_spec}

{prospective_rules}

{quality_rules}

Output: a single JSON object (not an array)"""


# ── Normalization ────────────────────────────────────────────────────────────

VALID_MEMORY_TYPES = {"episodic", "semantic", "procedural", "prospective"}
VALID_SUBTYPES = {"observation", "inference", "user_explicit", "agent_generated"}
VALID_SOURCE_TYPES = {"observation", "inference", "user_explicit", "external_api"}


def normalize(item: dict, namespace: str) -> dict | None:
    """Validate and normalize a Gemini-generated record."""
    content = str(item.get("content_text", "")).strip()
    if not content:
        return None

    memory_type = item.get("memory_type", "episodic")
    if memory_type not in VALID_MEMORY_TYPES:
        memory_type = "episodic"

    subtype = item.get("memory_subtype", "observation")
    if subtype not in VALID_SUBTYPES:
        subtype = "observation"

    source_type = item.get("source_type", "observation")
    if source_type not in VALID_SOURCE_TYPES:
        source_type = "observation"

    confidence = item.get("confidence", 0.8)
    if not isinstance(confidence, (int, float)):
        confidence = 0.8
    confidence = max(0.0, min(1.0, float(confidence)))

    tags = item.get("tags", [])
    if not isinstance(tags, list):
        tags = []
    tags = [str(t).lower().strip() for t in tags[:4] if t]

    entities = item.get("entities", [])
    if not isinstance(entities, list):
        entities = []
    entities = [str(e).strip() for e in entities[:3] if e]

    summary = str(item.get("summary", content[:150])).strip()
    if len(summary) > 200:
        summary = summary[:197] + "..."

    record: dict = {
        "namespace": namespace,
        "content_text": content,
        "summary": summary,
        "memory_type": memory_type,
        "memory_subtype": subtype,
        "content_type": "text",
        "confidence": round(confidence, 4),
        "source_type": source_type,
        "source_id": f"session:{uuid.uuid4().hex[:8]}",
        "tags": tags,
        "entities": entities,
        "language": "en",
        "importance_score": round(
            max(0.6, confidence * 0.9)
            if memory_type == "procedural"
            else max(0.3, confidence * 0.8),
            4,
        ),
        "decay_score": 1.0
        if memory_type == "prospective"
        else round(max(0.3, min(1.0, confidence * 1.1)), 4),
    }

    if memory_type == "prospective":
        trigger_type = item.get("trigger_type", "time")
        if trigger_type not in ("time", "condition"):
            trigger_type = "time"
        record["trigger_type"] = trigger_type
        trigger_at = item.get("trigger_at")
        if trigger_at:
            try:
                datetime.fromisoformat(str(trigger_at).replace("Z", "+00:00"))
                record["trigger_at"] = str(trigger_at)
            except ValueError:
                record["trigger_at"] = (
                    datetime.now(UTC) + timedelta(days=14)
                ).isoformat()
        else:
            record["trigger_at"] = (datetime.now(UTC) + timedelta(days=14)).isoformat()
        if trigger_type == "condition":
            record["trigger_condition"] = str(
                item.get("trigger_condition", "check status")
            )

    return record


def parse_json_response(raw: str) -> list[dict]:
    """Parse a Gemini JSON response, handling markdown fences and single objects."""
    raw = raw.strip()
    if raw.startswith("```"):
        raw = raw.split("\n", 1)[1] if "\n" in raw else raw[3:]
    if raw.endswith("```"):
        raw = raw.rsplit("```", 1)[0]
    raw = raw.strip()

    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError:
        return []

    if isinstance(parsed, list):
        return parsed
    if isinstance(parsed, dict):
        return [parsed]
    return []


def prompt_kwargs(persona: str) -> dict[str, str]:
    """Common prompt template kwargs."""
    return {
        "persona": persona,
        "field_spec": _FIELD_SPEC,
        "distribution_rules": _DISTRIBUTION_RULES,
        "prospective_rules": _PROSPECTIVE_RULES.format(
            today=datetime.now(UTC).strftime("%Y-%m-%d")
        ),
        "quality_rules": _QUALITY_RULES,
    }


# ── Batch mode ───────────────────────────────────────────────────────────────


async def generate_batch_mode(
    client: genai.Client,
    model: str,
    persona: str,
    namespace: str,
    total: int,
    batch_size: int,
    output_path: Path,
) -> int:
    """Generate records N-at-a-time via batch API calls."""
    config = genai.types.GenerateContentConfig(
        response_mime_type="application/json", temperature=1.0
    )
    kwargs = prompt_kwargs(persona)
    written = 0

    with open(output_path, "w") as f:
        while written < total:
            count = min(batch_size, total - written)
            prompt = BATCH_PROMPT.format(count=count, **kwargs)

            click.echo(
                f"  [{written + 1}–{written + count}/{total}] Generating batch...",
                err=True,
            )

            try:
                resp = await client.aio.models.generate_content(
                    model=model, contents=prompt, config=config
                )
                items = parse_json_response(resp.text or "[]")
            except Exception as e:
                click.echo(f"  [error] {e} — retrying in 5s", err=True)
                await asyncio.sleep(5)
                continue

            if not items:
                click.echo(f"  [warn] Empty response — retrying in 3s", err=True)
                await asyncio.sleep(3)
                continue

            for item in items:
                rec = normalize(item, namespace)
                if rec:
                    f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                    written += 1
                    if written >= total:
                        break

            if written < total:
                await asyncio.sleep(2)

    return written


# ── Async (single-record) mode ───────────────────────────────────────────────

# Assign a memory_type per index following the target distribution
_TYPE_WEIGHTS = [
    ("episodic", 50),
    ("semantic", 30),
    ("procedural", 12),
    ("prospective", 8),
]
_TYPE_POOL: list[str] = []
for _t, _w in _TYPE_WEIGHTS:
    _TYPE_POOL.extend([_t] * _w)


def pick_type(index: int) -> str:
    """Deterministic but distributed type selection."""
    return _TYPE_POOL[index % len(_TYPE_POOL)]


async def generate_one(
    client: genai.Client,
    model: str,
    persona: str,
    namespace: str,
    memory_type: str,
    semaphore: asyncio.Semaphore,
    config: genai.types.GenerateContentConfig,
    kwargs: dict[str, str],
) -> dict | None:
    """Generate a single record with semaphore-controlled concurrency."""
    prompt = SINGLE_PROMPT.format(memory_type=memory_type, **kwargs)

    async with semaphore:
        try:
            resp = await client.aio.models.generate_content(
                model=model, contents=prompt, config=config
            )
            items = parse_json_response(resp.text or "{}")
            if items:
                rec = normalize(items[0], namespace)
                if rec:
                    # Force the requested type in case the LLM drifted
                    rec["memory_type"] = memory_type
                    return rec
        except Exception:
            pass  # Will be counted as a failure by the caller
    return None


async def generate_async_mode(
    client: genai.Client,
    model: str,
    persona: str,
    namespace: str,
    total: int,
    concurrency: int,
    output_path: Path,
) -> int:
    """Generate records one-at-a-time, concurrently with a semaphore."""
    semaphore = asyncio.Semaphore(concurrency)
    config = genai.types.GenerateContentConfig(
        response_mime_type="application/json", temperature=1.0
    )
    kwargs = prompt_kwargs(persona)

    click.echo(
        f"  Launching {total} async tasks (concurrency={concurrency})...", err=True
    )

    tasks = [
        generate_one(
            client, model, persona, namespace, pick_type(i), semaphore, config, kwargs
        )
        for i in range(total)
    ]

    written = 0
    failed = 0
    with open(output_path, "w") as f:
        for i, coro in enumerate(asyncio.as_completed(tasks)):
            rec = await coro
            if rec:
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                written += 1
            else:
                failed += 1

            done = i + 1
            if done % 10 == 0 or done == total:
                click.echo(
                    f"\r  Progress: {done}/{total} ({written} ok, {failed} fail)   ",
                    nl=False,
                    err=True,
                )

    click.echo(err=True)  # Newline after progress

    if failed:
        click.echo(f"  [info] {failed} records failed — retrying...", err=True)
        retry_tasks = [
            generate_one(
                client,
                model,
                persona,
                namespace,
                pick_type(written + j),
                semaphore,
                config,
                kwargs,
            )
            for j in range(failed)
        ]
        with open(output_path, "a") as f:
            for coro in asyncio.as_completed(retry_tasks):
                rec = await coro
                if rec:
                    f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                    written += 1

    return written


# ── CLI ──────────────────────────────────────────────────────────────────────

DEFAULT_PERSONA = (
    "A machine learning engineer with 5 years of experience in data science, "
    "now studying generative AI. Daily work includes training ML models "
    "(XGBoost, LightGBM, neural networks) for production, evaluating business "
    "impact via A/B tests and metrics (conversion rate, churn, revenue), and "
    "studying the latest LLM papers from arxiv. Uses Python, PyTorch, "
    "Weights & Biases, MLflow, and cloud GPUs. Interested in RAG, "
    "fine-tuning, prompt engineering, and AI safety."
)


@click.command()
@click.option(
    "--num", default=100, show_default=True, help="Number of records to generate."
)
@click.option(
    "--mode",
    type=click.Choice(["batch", "async"], case_sensitive=False),
    default="batch",
    show_default=True,
    help="Generation mode: batch (N records per call) or async (1 record per call, concurrent).",
)
@click.option(
    "--batch-size",
    default=20,
    show_default=True,
    help="Records per API call (batch mode only).",
)
@click.option(
    "--concurrency",
    "-c",
    default=5,
    show_default=True,
    help="Max concurrent API calls (async mode only).",
)
@click.option("--persona", default=None, help="Persona description string.")
@click.option(
    "--persona-file",
    type=click.Path(exists=True, dir_okay=False),
    default=None,
    help="Read persona from a text file.",
)
@click.option(
    "--namespace",
    default="user:default",
    show_default=True,
    help="Namespace for all records.",
)
@click.option(
    "--output",
    "-o",
    default="data/sample_memories.jsonl",
    show_default=True,
    help="Output JSONL file path.",
)
@click.option(
    "--model",
    default="gemini-3-flash-preview",
    help="Gemini model. [default: GEMINI_LLM_MODEL env or gemini-3-flash-preview]",
)
@click.option(
    "--api-key", default=None, help="Gemini API key. [default: GEMINI_API_KEY env]"
)
def cli(
    num: int,
    mode: str,
    batch_size: int,
    concurrency: int,
    persona: str | None,
    persona_file: str | None,
    namespace: str,
    output: str,
    model: str | None,
    api_key: str | None,
) -> None:
    """Generate synthetic DSE memory records using Gemini.

    \b
    Modes:
      batch  — One API call returns N records as a JSON array.
               Fewer API calls, cheaper, but less diversity.
      async  — Each record is its own API call, run concurrently.
               Higher diversity, better for large datasets.

    \b
    Examples:
      python scripts/generate_dataset.py --num 100
      python scripts/generate_dataset.py --num 100 --mode async -c 8
      python scripts/generate_dataset.py --num 1000 --persona "A frontend dev"
      python scripts/generate_dataset.py --num 500 --persona-file persona.txt
    """
    resolved_key = api_key or os.environ.get("GEMINI_API_KEY", "")
    if not resolved_key:
        raise click.UsageError(
            "GEMINI_API_KEY not set. Pass --api-key or set the environment variable."
        )

    resolved_model = model or os.environ.get(
        "GEMINI_LLM_MODEL", "gemini-3-flash-preview"
    )

    if persona_file:
        resolved_persona = Path(persona_file).read_text().strip()
    elif persona:
        resolved_persona = persona
    else:
        resolved_persona = DEFAULT_PERSONA

    output_path = Path(output)

    click.echo("DSE Dataset Generator", err=True)
    click.echo(f"  Model:       {resolved_model}", err=True)
    click.echo(
        f"  Mode:        {mode}"
        + (
            f" (batch_size={batch_size})"
            if mode == "batch"
            else f" (concurrency={concurrency})"
        ),
        err=True,
    )
    click.echo(
        f"  Persona:     {resolved_persona[:70]}{'...' if len(resolved_persona) > 70 else ''}",
        err=True,
    )
    click.echo(f"  Namespace:   {namespace}", err=True)
    click.echo(f"  Records:     {num}", err=True)
    click.echo(f"  Output:      {output_path}", err=True)
    click.echo(err=True)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    client = genai.Client(api_key=resolved_key)
    start = time.monotonic()

    if mode == "batch":
        written = asyncio.run(
            generate_batch_mode(
                client,
                resolved_model,
                resolved_persona,
                namespace,
                num,
                batch_size,
                output_path,
            )
        )
    else:
        written = asyncio.run(
            generate_async_mode(
                client,
                resolved_model,
                resolved_persona,
                namespace,
                num,
                concurrency,
                output_path,
            )
        )

    elapsed = time.monotonic() - start

    # Summary
    counts: dict[str, int] = {}
    with open(output_path) as f:
        for line in f:
            r = json.loads(line)
            counts[r["memory_type"]] = counts.get(r["memory_type"], 0) + 1

    click.echo(
        f"\nDone. {written} records in {elapsed:.1f}s ({written / elapsed:.1f} rec/s)",
        err=True,
    )
    click.echo(
        f"  File: {output_path} ({output_path.stat().st_size / 1024:.0f} KB)", err=True
    )
    click.echo(f"  Distribution:", err=True)
    for mt, c in sorted(counts.items(), key=lambda x: -x[1]):
        click.echo(f"    {mt:15s} {c:5d}  ({c / max(written, 1) * 100:.1f}%)", err=True)


if __name__ == "__main__":
    cli()
